import { test, expect } from "@playwright/test";

test("ChemLab AI answers a chemistry question and a follow-up using live Gemini", async ({ page }) => {
  test.skip(process.env.CHECK_LIVE_AI !== "1", "Explicit opt-in: makes live provider requests.");
  test.setTimeout(100000);
  await page.goto("/en/experiments/red-cabbage-ph-indicator?tab=tutor");
  const input = page.getByRole("textbox", { name: "Ask ChemLab AI", exact: true });
  await expect(input).toBeVisible();
  for (const question of ["What is the difference between an atom and an ion?", "Give one simple example of each from your previous answer."]) {
    await input.fill(question);
    const pending = page.waitForResponse(response => response.url().endsWith("/api/ai/tutor") && response.request().method() === "POST", { timeout: 40000 });
    await page.getByRole("button", { name: "Ask", exact: true }).click();
    const response = await pending;
    expect(response.status()).toBe(200);
    const result = await response.json();
    expect(result.providerMode, "The response must be generated by Gemini, not the reference fallback").toBe("gemini_live");
    expect(result.answer.length).toBeGreaterThan(40);
    await expect(page.getByText(result.answer, { exact: true })).toBeVisible();
    console.log(JSON.stringify({ provider: result.providerMode, model: result.modelName, answer: result.answer }));
  }
  await expect(page.getByText("ChemLab AI · Live AI", { exact: true })).toHaveCount(2);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.screenshot({ path: `test-results/ai-live-${test.info().project.name}.png`, fullPage: true });
});
